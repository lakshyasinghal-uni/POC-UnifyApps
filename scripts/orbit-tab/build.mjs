#!/usr/bin/env node
// Rebuild scripts/orbit-tab/bundle.js from scripts/orbit-api.mjs. Run after any change to orbit-api.mjs:
//   cd scripts/orbit-tab && npm i --no-save esbuild buffer path-browserify && node build.mjs
// bundle.js is committed, so nobody needs npm to use the tab transport.
import { build } from "esbuild";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "..", "orbit-api.mjs");
const hash = crypto.createHash("sha256").update(fs.readFileSync(src)).digest("hex").slice(0, 16);
const r = await build({
  entryPoints: [src], bundle: true, write: false, format: "iife", platform: "browser", target: "es2020", minify: true,
  alias: { "node:fs": path.join(here, "shim-fs.js"), "node:path": "path-browserify" },
  inject: [path.join(here, "shim-process.js"), path.join(here, "shim-buffer.js")],
  define: { "import.meta.url": JSON.stringify("file:///plugin/scripts/orbit-api.mjs") },
  nodePaths: [path.join(here, "node_modules")], logLevel: "warning",
});
const code = r.outputFiles[0].text.replace(/^#!.*\n/, ""); // the loader wraps it in a function
fs.writeFileSync(path.join(here, "bundle.js"), `// GENERATED by scripts/orbit-tab/build.mjs from scripts/orbit-api.mjs — do not edit.\n// source-sha256: ${hash}\n${code}`);
console.log(JSON.stringify({ ok: true, bundle: "scripts/orbit-tab/bundle.js", bytes: code.length, source: hash }));
