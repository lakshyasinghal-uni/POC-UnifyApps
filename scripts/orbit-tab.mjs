#!/usr/bin/env node
/**
 * orbit-tab.mjs — run any orbit-api.mjs command inside a browser tab that is signed in to Orbit.
 *
 * Why: the shell cannot use the browser's sign-in, and a page cannot call this machine (the
 * browser blocks localhost). So the command itself runs in the tab: same-origin calls carry the
 * session cookie, the cookie never leaves the browser, and nothing is pasted into the chat.
 *
 * Steps (the browser's JavaScript tool runs each snippet in the signed-in Orbit tab):
 *   1. node scripts/orbit-tab.mjs loader
 *        writes studio/.orbit-tab/loader.js. Run its contents in the tab once (again after a
 *        page reload, or when a call answers {"needLoader":true}).
 *   2. node scripts/orbit-tab.mjs call <orbit-api command and args, exactly as for orbit-api.mjs>
 *        prints {start, poll, wait}. Run `start` in the tab, then `poll` until it returns
 *        "done":true (or `wait` where the JavaScript tool awaits promises).
 *   3. Save the poll result to a file and run: node scripts/orbit-tab.mjs apply <file>
 *        it writes back every file the command wrote (queue, schema cache, reports, fetch-doc
 *        output), prints the command's JSON line, and exits with the command's exit code.
 *
 * Local files a command reads (@file JSON, --file, upload <path>, --feedback @file, the write
 * queue) are read here and sent with the call, so the tab sees the same files the shell would.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const OUT_DIR = path.resolve("studio", ".orbit-tab");
const PLUGIN_FILES = ["skills/build/references/orbit-contract.json", "skills/build/references/orbit-objects.json"];
const PASS_ENV = ["ORBIT_EXPECT", "ORBIT_TAKEOVER_HOURS", "ORBIT_BUCKET", "ORBIT_IDP"];

const print = (o, code = 0) => { process.stdout.write(JSON.stringify(o) + "\n"); process.exit(code); };
const fail = (error, extra = {}) => print({ ok: false, error, ...extra }, 1);

// ---------- local path <-> path inside the tab ----------
const toVirtual = (p) => (path.isAbsolute(p) ? path.resolve(p) : path.posix.join("/work", p.split(path.sep).join("/")));
function toLocal(v) {
  if (v.startsWith("/plugin/")) return path.join(ROOT, v.slice("/plugin/".length));
  if (v === "/work" || v.startsWith("/work/")) return path.resolve(v.slice("/work/".length) || ".");
  return v;
}
const b64 = (buf) => Buffer.from(buf).toString("base64");

// ---------- the loader: bundle + plugin files + job runner ----------
function bundle() {
  const file = path.join(HERE, "orbit-tab", "bundle.js");
  const text = fs.readFileSync(file, "utf8");
  const built = (text.match(/source-sha256: ([0-9a-f]+)/) || [])[1];
  const now = crypto.createHash("sha256").update(fs.readFileSync(path.join(HERE, "orbit-api.mjs"))).digest("hex").slice(0, 16);
  if (built !== now) fail("scripts/orbit-tab/bundle.js is older than scripts/orbit-api.mjs. Rebuild it: cd scripts/orbit-tab && npm i --no-save esbuild buffer path-browserify && node build.mjs");
  return text;
}
function pluginFiles() {
  const o = {};
  for (const f of PLUGIN_FILES) o[`/plugin/${f}`] = JSON.stringify(JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8")));
  return o;
}
function versionOf(code, files) {
  return crypto.createHash("sha256").update(code).update(JSON.stringify(files)).digest("hex").slice(0, 12);
}
function loaderSource() {
  const code = bundle();
  const files = pluginFiles();
  const version = versionOf(code, files);
  const src = `/* POC Studio · Orbit tab loader ${version}. Generated by scripts/orbit-tab.mjs loader. Defines window.__orbitTab. */
(() => {
  const VERSION = ${JSON.stringify(version)};
  const PLUGIN_FILES = ${JSON.stringify(files)};
  const MAIN = function () {
${code}
  };
  const fromB64 = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));
  const toB64 = (u) => { let s = ""; for (let i = 0; i < u.length; i += 0x8000) s += String.fromCharCode.apply(null, u.subarray(i, i + 0x8000)); return btoa(s); };
  const jobs = {};
  // orbit-api ends a run with process.exit; here that throws EXIT to stop the code after it.
  // When that happens inside a promise callback, the rejection is expected: keep it out of the console.
  const EXIT = new Error("orbit-api exited");
  if (typeof window.addEventListener === "function") window.addEventListener("unhandledrejection", (e) => { if (e.reason === EXIT) e.preventDefault(); });
  let chain = Promise.resolve();
  function runOne(req) {
    return new Promise((resolve) => {
      const files = new Map();
      for (const [k, v] of Object.entries(PLUGIN_FILES)) files.set(k, new TextEncoder().encode(v));
      for (const [k, v] of Object.entries(req.files || {})) files.set(k, fromB64(v));
      const written = new Set();
      let done = false, stdout = "", stderr = "";
      const finish = (code) => {
        const writes = {};
        for (const k of written) writes[k] = toB64(new Uint8Array(files.get(k)));
        resolve({ done: true, code, stdout, stderr, writes });
      };
      globalThis.__ORBIT_TAB__ = true;
      globalThis.__ORBIT_CTX__ = {
        argv: req.argv, env: { ...(req.env || {}), ORBIT_BASE: location.origin }, files, written,
        out: (s) => { if (!done) stdout += s; }, err: (s) => { if (!done) stderr += s; },
        // The first exit ends the run; it throws so the code after it stops, as in Node.
        exit: (code) => { if (done) return; done = true; finish(code); throw EXIT; },
      };
      try { MAIN(); } catch (e) { if (e !== EXIT && !done) { done = true; stdout = JSON.stringify({ ok: false, error: String((e && e.message) || e) }) + "\\n"; finish(1); } }
    });
  }
  window.__orbitTab = {
    version: VERSION,
    start(id, req) {
      jobs[id] = { done: false, started: Date.now() };
      chain = chain.then(() => runOne(req)).then((r) => { jobs[id] = r; },
        (e) => { jobs[id] = { done: true, code: 1, stdout: JSON.stringify({ ok: false, error: String((e && e.message) || e) }) + "\\n", stderr: "", writes: {} }; });
      return id;
    },
    poll(id) { const j = jobs[id]; return JSON.stringify(j ? (j.done ? { id, ...j } : { id, done: false, seconds: Math.round((Date.now() - j.started) / 1000) }) : { id, done: false, unknown: true }); },
    async wait(id) { while (!(jobs[id] && jobs[id].done)) await new Promise((r) => setTimeout(r, 500)); return this.poll(id); },
  };
  return "POC Studio Orbit tab loader " + VERSION + " ready";
})();
`;
  return { src, version };
}

// ---------- which local files a command reads ----------
function filesFor(args) {
  const want = new Set();
  const cmd = args[0];
  for (let i = 1; i < args.length; i++) {
    const a = args[i];
    if (a.startsWith("--")) {
      const k = a.slice(2), v = args[i + 1];
      if (v !== undefined && !v.startsWith("--")) {
        i++;
        if (k === "file") want.add(v);
        if (k === "feedback" && v.startsWith("@")) want.add(v.slice(1));
      }
    } else if (a.startsWith("@")) want.add(a.slice(1));
    else if (cmd === "upload" && i === 1) want.add(a);
  }
  const queue = process.env.ORBIT_QUEUE || path.join("studio", ".orbit-queue.jsonl");
  const extras = [queue, queue.replace(/\.jsonl$/, "") + ".dead.jsonl", path.join(path.dirname(queue), ".orbit-schema-cache.json")];
  const files = {};
  for (const f of want) {
    if (!fs.existsSync(f)) fail(`File not found: ${f}`);
    files[toVirtual(f)] = b64(fs.readFileSync(f));
  }
  for (const f of extras) if (fs.existsSync(f)) files[toVirtual(f)] = b64(fs.readFileSync(f));
  return files;
}
// Paths in the arguments are rewritten to the tab's paths, so the command reads what was sent.
function rewriteArgs(args) {
  const cmd = args[0], out = [cmd];
  for (let i = 1; i < args.length; i++) {
    const a = args[i];
    if (a.startsWith("--")) {
      out.push(a);
      const k = a.slice(2), v = args[i + 1];
      if (v !== undefined && !v.startsWith("--")) {
        i++;
        if (k === "file" || k === "out") out.push(toVirtual(v));
        else if (k === "feedback" && v.startsWith("@")) out.push("@" + toVirtual(v.slice(1)));
        else out.push(v);
      }
    } else if (a.startsWith("@")) out.push("@" + toVirtual(a.slice(1)));
    else if (cmd === "upload" && i === 1) out.push(toVirtual(a));
    else out.push(a);
  }
  return out;
}

// ---------- commands ----------
const [sub, ...rest] = process.argv.slice(2);
switch (sub) {
  case "loader": {
    const { src, version } = loaderSource();
    fs.mkdirSync(OUT_DIR, { recursive: true });
    const file = path.join(OUT_DIR, "loader.js");
    fs.writeFileSync(file, src);
    print({ ok: true, version, loader: file, bytes: src.length,
      next: "Run the whole of this file with the browser's JavaScript tool in the signed-in Orbit tab. It answers 'POC Studio Orbit tab loader <version> ready'." });
  }
  case "call": {
    if (!rest.length) fail("call needs an orbit-api.mjs command, e.g. call check");
    const { version } = loaderSource();
    const env = {};
    for (const k of PASS_ENV) if (process.env[k]) env[k] = process.env[k];
    if (process.env.ORBIT_QUEUE) env.ORBIT_QUEUE = toVirtual(process.env.ORBIT_QUEUE);
    const req = { argv: rewriteArgs(rest), env, files: filesFor(rest) };
    const id = `${rest[0]}-${Date.now().toString(36)}-${crypto.randomBytes(3).toString("hex")}`;
    const guard = `(typeof window.__orbitTab === "undefined" || window.__orbitTab.version !== ${JSON.stringify(version)})`;
    print({ ok: true, id, version,
      start: `${guard} ? JSON.stringify({ needLoader: true }) : window.__orbitTab.start(${JSON.stringify(id)}, ${JSON.stringify(req)})`,
      poll: `window.__orbitTab.poll(${JSON.stringify(id)})`,
      wait: `await window.__orbitTab.wait(${JSON.stringify(id)})`,
      next: "Run `start` in the Orbit tab, then `poll` until done is true. Save that result to a file and run: node scripts/orbit-tab.mjs apply <file>" });
  }
  case "apply": {
    const src = rest[0] && rest[0] !== "-" ? fs.readFileSync(rest[0], "utf8") : fs.readFileSync(0, "utf8");
    let r = null;
    for (const t of [src.trim(), src.slice(src.indexOf("{"), src.lastIndexOf("}") + 1), src.slice(src.indexOf('"'), src.lastIndexOf('"') + 1)]) {
      try { let x = JSON.parse(t); if (typeof x === "string") x = JSON.parse(x); if (x && typeof x === "object") { r = x; break; } } catch {}
    }
    if (!r) fail("apply could not read a poll result. Save exactly what poll returned.");
    if (!r.done) print({ ok: false, pending: true, error: "The command is still running in the tab; poll again." }, 1);
    const written = [];
    for (const [v, data] of Object.entries(r.writes || {})) {
      const local = toLocal(v);
      fs.mkdirSync(path.dirname(local), { recursive: true });
      fs.writeFileSync(local, Buffer.from(data, "base64"));
      written.push(path.relative(process.cwd(), local) || local);
    }
    if (r.stderr) process.stderr.write(r.stderr);
    let line = {};
    try { line = JSON.parse(String(r.stdout || "").trim().split("\n").pop()); } catch { line = { ok: false, error: `unreadable output: ${String(r.stdout).slice(0, 300)}` }; }
    if (written.length) line.filesWritten = written;
    // Paths inside the tab are shown as local paths.
    const s = JSON.stringify(line).replaceAll('"/work/', `"${process.cwd().replaceAll("\\", "/")}/`).replaceAll("\"/work\"", JSON.stringify(process.cwd()));
    process.stdout.write(s + "\n");
    process.exit(Number(r.code) || 0);
  }
  default:
    fail(`unknown command "${sub || ""}". Use: loader | call <orbit-api command…> | apply <poll result file>`);
}
