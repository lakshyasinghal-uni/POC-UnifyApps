"""Bake Qatar's municipality boundaries into pulse-map.es.js (between the GEO:BEGIN / GEO:END markers).

    python build_geo.py [path/to/geoBoundaries-QAT-ADM1_simplified.geojson]

Without an argument it downloads the file from geoBoundaries (gbOpen, CC BY 4.0). Note: the
raw.githubusercontent.com URL returns a Git-LFS pointer — media.githubusercontent.com serves the data.
The geometry is projected here (equirectangular, x scaled by cos 25.3°) and simplified
(Douglas-Peucker), so the component ships SVG paths and never fetches anything at runtime.
geoBoundaries spells names its own way; ALIAS maps them to the region codes (the sample's cgbp_region object, examples/cgb-pulse/).
This file is not part of the uploaded ZIP (pack_component.py packs out.json + main + style only).
"""
import json
import math
import os
import re
import sys
import urllib.request

URL = ('https://media.githubusercontent.com/media/wmgeolab/geoBoundaries/main/releaseData/gbOpen/'
       'QAT/ADM1/geoBoundaries-QAT-ADM1_simplified.geojson')
ALIAS = {'Doha': 'DOHA', 'Al Rayyan': 'RAYYAN', 'Al Wakra': 'WAKRAH', 'Al Daayen': 'DAAYEN', 'Umm Slal': 'UMMSALAL',
         'Al Khor and Al Thakhira': 'KHOR', 'Al Shamal': 'SHAMAL', 'Al Sheehaniya': 'SHAHANIYA'}
S = 200.0                      # SVG units per degree of latitude
K = math.cos(math.radians(25.3))
TOL = 0.45                     # simplification tolerance in SVG units
MIN_RING_AREA = 1.5            # drop specks (tiny islets) smaller than this, in SVG units²
HERE = os.path.dirname(os.path.abspath(__file__))


def load():
    if len(sys.argv) > 1:
        return json.load(open(sys.argv[1], encoding='utf-8'))
    with urllib.request.urlopen(URL) as r:
        return json.loads(r.read().decode('utf-8'))


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    best, idx = -1.0, 0
    for i in range(1, len(pts) - 1):
        x, y = pts[i]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / norm
        if d > best:
            best, idx = d, i
    if best <= tol:
        return [pts[0], pts[-1]]
    return dp(pts[:idx + 1], tol)[:-1] + dp(pts[idx:], tol)


def simplify_ring(pts, tol):
    # A closed ring has no baseline (start == end), so split it at the point farthest from the start
    # and simplify the two open halves.
    far = max(range(len(pts)), key=lambda i: math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]))
    a = dp(pts[:far + 1], tol)
    b = dp(pts[far:] + [pts[0]], tol)
    return a[:-1] + b[:-1]


def area(ring):
    return 0.5 * sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]))


def centroid(ring):
    a = area(ring) or 1e-9
    cx = sum((x1 + x2) * (x1 * y2 - x2 * y1) for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1])) / (6 * a)
    cy = sum((y1 + y2) * (x1 * y2 - x2 * y1) for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1])) / (6 * a)
    return cx, cy


def main():
    gj = load()
    feats = []
    for f in gj['features']:
        name = f['properties']['shapeName']
        code = ALIAS.get(name)
        if not code:
            sys.exit(f'no alias for {name!r} — add it to ALIAS')
        g = f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        feats.append((code, polys))
    lons = [p[0] for _, polys in feats for poly in polys for ring in poly for p in ring]
    lats = [p[1] for _, polys in feats for poly in polys for ring in poly for p in ring]
    lon0, lat1 = min(lons), max(lats)
    proj = lambda lon, lat: ((lon - lon0) * K * S, (lat1 - lat) * S)
    W, H = (max(lons) - lon0) * K * S, (lat1 - min(lats)) * S
    out, total = {}, 0
    for code, polys in feats:
        parts, big = [], (0, None)
        for poly in polys:
            for ri, ring in enumerate(poly):
                pts = [proj(*p[:2]) for p in ring]
                if pts[0] == pts[-1]:
                    pts = pts[:-1]
                a = abs(area(pts))
                if a < MIN_RING_AREA:
                    continue
                simple = simplify_ring(pts, TOL)
                if len(simple) < 3:
                    continue
                total += len(simple)
                parts.append('M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in simple) + 'Z')
                if ri == 0 and a > big[0]:
                    big = (a, pts)
        cx, cy = centroid(big[1])
        out[code] = {'d': ''.join(parts), 'cx': round(cx, 1), 'cy': round(cy, 1), 'area': round(big[0])}
    geo = {'w': round(W, 1), 'h': round(H, 1), 'regions': out}
    block = ('// GEO:BEGIN — generated by build_geo.py from geoBoundaries QAT ADM1 (CC BY 4.0). Do not edit by hand.\n'
             f'const GEO = {json.dumps(geo, separators=(",", ":"))};\n// GEO:END')
    path = os.path.join(HERE, 'pulse-map.es.js')
    src = open(path, encoding='utf-8').read()
    src, n = re.subn(r'// GEO:BEGIN.*?// GEO:END', lambda _: block, src, flags=re.S)
    if n != 1:
        sys.exit('GEO:BEGIN / GEO:END markers not found in pulse-map.es.js')
    open(path, 'w', encoding='utf-8').write(src)
    print(f'{len(out)} municipalities, {total} points, {len(block) / 1024:.1f} KB of geometry, viewBox {W:.0f} x {H:.0f}')
    for code, r in sorted(out.items(), key=lambda kv: -kv[1]['area']):
        print(f'  {code:10} area {r["area"]:>6}  centroid ({r["cx"]}, {r["cy"]})')


if __name__ == '__main__':
    main()
